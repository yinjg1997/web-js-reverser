// call 方法：“临时借用”，立即执行
// call 可以理解为：临时让函数 “借用” 另一个对象的身份执行，并且调用后立即执行函数。
// 函数名.call(要指向的this对象, 参数1, 参数2, ...);



// bind 方法：“永久绑定”，返回新函数
// bind 可以理解为：给函数 “绑定” 一个固定的 this，返回一个新函数，需要手动调用才执行。
// const 新函数 = 原函数.bind(要指向的this对象, 参数1, 参数2, ...);


/**
  ┌───────┬────────────┬────────────────────────────────┬──────────────────────┐
  │       │  执行时机  │            参数形式            │        返回值        │
  ├───────┼────────────┼────────────────────────────────┼──────────────────────┤
  │ call  │ 立即执行   │ 逐个列举 fn.call(obj, a, b)    │ 函数返回值           │
  ├───────┼────────────┼────────────────────────────────┼──────────────────────┤
  │ apply │ 立即执行   │ 数组传递 fn.apply(obj, [a, b]) │ 函数返回值           │
  ├───────┼────────────┼────────────────────────────────┼──────────────────────┤
  │ bind  │ 返回新函数 │ 逐个列举 fn.bind(obj, a, b)    │ 新函数（需手动调用） │
  └───────┴────────────┴────────────────────────────────┴──────────────────────┘
 */